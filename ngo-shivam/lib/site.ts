/**
 * Single source of truth for site-wide SEO settings.
 * Used by: app/layout.tsx, app/robots.ts, app/sitemap.ts, lib/seo.ts and every page's metadata / structured data.
 *
 * IMPORTANT: set NEXT_PUBLIC_SITE_URL (for example https://www.yourdomain.org, no trailing slash)
 * in .env.local AND in your hosting panel's Environment Variables, then rebuild.
 * It becomes the base of every canonical URL, the sitemap and the social-share links.
 */
import { CONTACT } from "@/lib/org";

function resolveSiteUrl(): string {
    const raw = process.env.NEXT_PUBLIC_SITE_URL?.trim();
    if (raw) return raw.replace(/\/+$/, "");
    if (process.env.NODE_ENV === "production") {
        throw new Error(
            "NEXT_PUBLIC_SITE_URL is not set. Add it to your environment variables (e.g. https://www.yourdomain.org) so canonical URLs and the sitemap use your real domain.",
        );
    }
    return "http://localhost:3000";
}

